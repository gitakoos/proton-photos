package eu.akoos.photos.data.api

import androidx.test.core.app.ApplicationProvider
import org.junit.Assert.assertFalse
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
class PhotosApiClientTest {

    /**
     * The body-level HTTP logger this switch adds drains the Drive SDK's one-shot block upload stream, so
     * every block upload of a build with it on fails before anything reaches the server.
     */
    @Test
    fun `core HTTP debug logging stays off`() {
        assertFalse(PhotosApiClient(ApplicationProvider.getApplicationContext()).enableDebugLogging)
    }
}
