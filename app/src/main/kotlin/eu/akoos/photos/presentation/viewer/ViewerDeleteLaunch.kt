package eu.akoos.photos.presentation.viewer

import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.Job
import kotlinx.coroutines.launch
import kotlin.coroutines.CoroutineContext

/**
 * Starts a viewer delete in this app-wide scope rather than the view model's, so a delete still waiting on
 * Drive or the media store finishes when the user leaves the viewer. It stays on the main thread the view
 * model's own work runs on.
 */
internal fun CoroutineScope.launchViewerDelete(
    context: CoroutineContext = Dispatchers.Main.immediate,
    block: suspend CoroutineScope.() -> Unit,
): Job = launch(context, block = block)
